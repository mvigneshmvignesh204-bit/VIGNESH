
color_list = ["Red", "Green", "Blue", "Black", "White"]
number_list = [10, 24, 76, 23, 12]
list_size = len(color_list)
print(f"The list of colors: {color_list}")
print(f"The size of the list is: {list_size}") #
print(f"\nThe list of numbers: {number_list}")
greatest_value = max(number_list)
print(f"The greatest value in the list is: {greatest_value}")
minimum_value = min(number_list)
print(f"The minimum value in the list is: {minimum_value}")
total_sum = sum(number_list)
print(f"The sum of all elements in the list is: {total_sum}")
